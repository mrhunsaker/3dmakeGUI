#!/usr/bin/env python3
"""Generate docs/cli-equivalents.md from the committed 3dm spec."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = json.loads((ROOT / "src/tdmake_gui_wrapper/data/3dm_spec.json").read_text(encoding="utf-8"))

GUI_CONTROL = {
    "setup": "Settings > Run Setup (terminal)",
    "new": "Quick Actions > New Project (terminal)",
    "build": "Quick Actions > Build STL / Build + Slice / Full Pipeline",
    "orient": "Quick Actions > Orient / Orient + Preview / Full Pipeline",
    "info": "Quick Actions > Describe (Info); Command Options > Interactive info",
    "image": "Image Export > Run Image Export",
    "preview": "Quick Actions > Preview / Preview + Slice / Preview + Print",
    "slice": "Quick Actions > Slice / Build + Slice / Full Pipeline",
    "print": "Quick Actions > Print / Preview + Print",
    "list-profiles": "Settings > List Profiles",
    "list-overlays": "Settings > List Overlays",
    "edit-model": "Settings > Edit Model (3dm) (terminal)",
    "edit-overlay": "Settings > Edit Overlay (terminal)",
    "edit-profile": "Settings > Edit Profile (terminal)",
    "clone-profile": "Settings > Clone Profile (terminal)",
    "edit-profile-gcode": "Settings > Edit Profile GCODE (terminal)",
    "edit-prompt": "Settings > Edit AI Prompt (terminal)",
    "edit-global-config": "Settings > Edit Global Config (3dm) (terminal)",
    "list-libraries": "Settings > List Libraries",
    "install-libraries": "Settings > Install Libraries",
    "test-connect": "Settings > Test Connection",
    "install-profile": "Settings > Install Profile (terminal)",
    "self-update": "Settings > Self Update",
    "help": "Settings > 3dm Help",
    "version": "Settings > Version Info",
}
FLAG_CONTROL = {
    "scale": "Command Options > Scale (-s)",
    "scale_x": "Command Options > Scale X", "scale_y": "Command Options > Scale Y", "scale_z": "Command Options > Scale Z",
    "model": "Command Options > Model name (-m)", "view": "Command Options > View (-v; silhouettes or plane names)",
    "profile": "Command Options > Profile (-p)", "overlay": "Command Options > Overlays (-o, comma separated)",
    "angle": "Image Export > Camera angles (also info via switch)", "interactive": "Command Options > Interactive info (-i)",
    "copies": "Command Options > Copies (-c)", "colorscheme": "Image Export > Color scheme (also info via switch)",
    "image_size": "Image Export > Image size (also info via switch)", "debug": "Command Options > Enable debug",
    "help": "Settings > 3dm Help", "h": "Settings > 3dm Help", "version": "Settings > Version Info",
}  # fmt: skip

lines = [
    "# 3dm CLI equivalents",
    "",
    "Generated by `scripts/gen_cli_docs.py` from `3dm_spec.json` (itself generated from the 3dmake source). Do not edit.",
    "",
    "Every control runs the real `3dm` with an argument list (no shell). The exact command is echoed as `[RUN] ...` in the Output Log.",
    "Actions marked *terminal* read from stdin or launch an editor, so the GUI opens them in a system terminal.",
    "",
    "## Actions",
    "",
    "| 3dm action | Kind | Input files | GUI control |",
    "|---|---|---|---|",
]
for a in spec["actions"]:
    if a["internal"]:
        continue
    kind = "isolated" if a["isolated"] else ("pipeline, last in chain" if a["last_in_chain"] else "pipeline")
    files = ", ".join(a["input_file_types"]) or "-"
    lines.append(f"| `{a['name']}` | {kind} | {files} | {GUI_CONTROL[a['name']]} |")
lines += ["", "## Global options", "", "| Flags | Repeatable | GUI control |", "|---|---|---|"]
for o in spec["options"]:
    lines.append(f"| `{' '.join(o['flags'])}` | {'yes' if o['repeatable'] else 'no'} | {FLAG_CONTROL.get(o['dest'], '?')} |")
(ROOT / "docs" / "cli-equivalents.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote docs/cli-equivalents.md")
